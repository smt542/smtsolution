/* 건물별·항목별 검침일 (건물 목록 / 건물 상세 공용 소스) */
(function () {
  var D = {
    '001': [15, 15, 15, 15], '002': [10, 12, 10, 12], '003': [20, 20, 18, 20],
    '004': [5, 8, 5, 8], '005': [25, 25, 22, 25], '006': [10, 10, 12, 10],
    '007': [18, 20, 18, 20], '008': [8, 8, 5, 8], '009': [15, 18, 15, 18],
    '010': [12, 12, 10, 12], '011': [20, 22, 20, 22], '012': [5, 5, 8, 5],
    '013': [25, 25, 25, 22], '014': [10, 12, 12, 10], '015': [18, 18, 15, 18],
    '016': [8, 10, 8, 10], '017': [15, 15, 12, 15], '018': [22, 22, 20, 22],
    '019': [12, 10, 12, 10], '020': [20, 18, 18, 20], '021': [5, 8, 8, 5],
    '022': [25, 22, 25, 25], '023': [10, 10, 8, 12], '024': [18, 20, 20, 18]
  };
  var K = ['수도', '공용전기', '전기', '가스'];
  window.ERP_METER_DAY = {
    kinds: K,
    /* 코드+항목 → 검침일(일). 없는 건물은 코드 기준 기본값 */
    get: function (code, kind) {
      var i = K.indexOf(kind);
      if (i < 0) return null;
      var c = String(code || '').trim();
      var r = D[c];
      if (r) return r[i];
      var base = parseInt(c, 10) || 1;
      return (base * 3 + i) % 25 + 3;
    },
    all: function (code) {
      var o = {}, self = this;
      K.forEach(function (k) { o[k] = self.get(code, k); });
      return o;
    }
  };
})();
