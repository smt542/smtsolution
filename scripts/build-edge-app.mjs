// Supabase Edge Function용 앱 코드 묶음 생성기.
//
// 예약 발송(dispatch-scheduled)·결과 재조회(delivery-reconcile) Edge Function이 앱과 **같은 코드**
// (lib/messaging/drainSchedules.ts, lib/messaging/reconcile.ts와 그 의존 파일)를 쓰도록
// supabase/functions/_shared/app/ 아래로 복사한다(생성물, git 제외).
//  - lib/popbill/sdk.ts → supabase/functions/_shared/popbill-rest.ts (팝빌 npm SDK는 Edge 번들 불가)
//  - lib/popbill/config.ts의 process.env → globalThis.__APP_ENV__ (Edge는 Vault에서 읽어 주입)
//  - "popbill" 타입 import → _shared/app/popbill-types.ts (types/popbill.d.ts에서 생성)
//
// 사용: node scripts/build-edge-app.mjs && npx supabase functions deploy <name> --use-api
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const outDir = path.join(root, "supabase/functions/_shared/app");
const ENTRIES = ["lib/messaging/drainSchedules.ts", "lib/messaging/reconcile.ts"];
const IMPORT_RE = /(?:import|export)\s[^'"]*?from\s+['"]([^'"]+)['"]/g;

function resolveSpec(spec, from) {
  let base;
  if (spec.startsWith("@/")) base = spec.slice(2);
  else if (spec.startsWith(".")) base = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec));
  else return null;
  for (const candidate of [`${base}.ts`, `${base}.tsx`, `${base}/index.ts`]) {
    if (fs.existsSync(path.join(root, candidate))) return candidate;
  }
  throw new Error(`unresolved import ${spec} from ${from}`);
}

const files = new Set();
const external = new Set();
function walk(file) {
  if (files.has(file)) return;
  files.add(file);
  if (file === "lib/popbill/sdk.ts") return; // 대체 구현으로 교체(원본 의존성은 따라가지 않음)
  const src = fs.readFileSync(path.join(root, file), "utf8");
  for (const match of src.matchAll(IMPORT_RE)) {
    const resolved = resolveSpec(match[1], file);
    if (resolved) walk(resolved);
    else external.add(match[1]);
  }
}
ENTRIES.forEach(walk);

const allowedExternal = new Set(["node:crypto", "popbill"]);
const unexpected = [...external].filter((spec) => !allowedExternal.has(spec));
if (unexpected.length > 0) throw new Error(`unexpected external imports: ${unexpected.join(", ")}`);

fs.rmSync(outDir, { recursive: true, force: true });
for (const file of files) {
  let src =
    file === "lib/popbill/sdk.ts"
      ? fs.readFileSync(path.join(root, "supabase/functions/_shared/popbill-rest.ts"), "utf8")
      : fs.readFileSync(path.join(root, file), "utf8");
  if (file === "lib/popbill/config.ts") {
    src = src.replaceAll(
      "process.env",
      "((globalThis as { __APP_ENV__?: Env }).__APP_ENV__ ?? {})",
    );
  }
  // 상대 경로 import로 바꿔 import map 없이도 묶음 안에서 해석되게 한다.
  src = src.replace(IMPORT_RE, (whole, spec) => {
    if (spec === "popbill") {
      const rel = path.posix.relative(path.posix.dirname(file), "popbill-types.ts");
      return whole.replace(`"${spec}"`, `"${rel.startsWith(".") ? rel : `./${rel}`}"`);
    }
    if (!spec.startsWith("@/") && !spec.startsWith(".")) return whole;
    const target = resolveSpec(spec, file);
    let rel = path.posix.relative(path.posix.dirname(file), target);
    if (!rel.startsWith(".")) rel = `./${rel}`;
    return whole.replace(/(['"])[^'"]+\1$/, `"${rel}"`);
  });
  const dest = path.join(outDir, file);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, `// GENERATED by scripts/build-edge-app.mjs — edit the source file, not this copy.\n${src}`);
}

// "popbill" 타입 모듈: types/popbill.d.ts의 declare module 본문을 일반 모듈로 옮긴다(함수 선언 제외).
const dts = fs.readFileSync(path.join(root, "types/popbill.d.ts"), "utf8");
const body = dts.slice(dts.indexOf("{", dts.indexOf('declare module "popbill"')) + 1, dts.lastIndexOf("}"));
const typesModule = body
  .split("\n")
  .filter((line) => !/^\s*export function /.test(line))
  .join("\n")
  .replaceAll("fileData: Buffer;", "fileData: Uint8Array;");
fs.writeFileSync(
  path.join(outDir, "popbill-types.ts"),
  `// GENERATED by scripts/build-edge-app.mjs from types/popbill.d.ts.\n${typesModule}\n`,
);

console.log(`edge app bundle: ${files.size} files → ${path.relative(root, outDir)}`);
