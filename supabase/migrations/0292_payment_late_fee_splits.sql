-- 수납 이력 「수.연」: 그 달 연체료를 별도 행(연체료 이전)으로 나눠 저장한다.
--
-- 연체료는 미납 원금으로 그때그때 계산하므로, 원금을 내고 나면 0이 되어 나눈 행을 다시 그릴 근거가 없었다.
-- 수.연을 누른 시점의 연체료를 미수금(payment_late_fee_splits)으로 고정해 두고, 그 행에서 받은 수납은
-- payments.late_fee_split_id 로 연결한다. 연결된 수납은 원금이 아니라 그 연체료를 낸 것으로 본다(화면 계산).
--
-- 1) payment_late_fee_splits (+ RLS 조회: payments 와 같은 범위)
-- 2) payments.late_fee_split_id
-- 3) create_late_fee_split / cancel_late_fee_split — 수납 권한, 감사 로그
-- 4) save_payment_history: op 'split'(나누기 + 선택 수납) · 'cancel_split', 'record' 연결, 'edit' 연결 유지
-- 5) get_payment_statement_data: payments.late_fee_split_id, late_fee_splits 반환

create table if not exists public.payment_late_fee_splits (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.organizations(id) on delete cascade,
  unit_id bigint not null references public.units(id) on delete cascade,
  period date not null check (period = date_trunc('month', period)::date),
  amount integer not null check (amount > 0),
  memo text,
  status text not null default 'active' check (status in ('active', 'canceled')),
  created_at timestamptz not null default now(),
  created_by uuid references public.profiles(user_id) on delete set null,
  canceled_at timestamptz,
  canceled_by uuid references public.profiles(user_id) on delete set null
);
comment on table public.payment_late_fee_splits is '수납 이력 수.연 — 그 달 연체료를 나눈 미수금(나눈 시점 금액 고정)';

create index if not exists payment_late_fee_splits_unit_period_idx
  on public.payment_late_fee_splits (unit_id, period);

alter table public.payment_late_fee_splits enable row level security;
drop policy if exists lfs_select on public.payment_late_fee_splits;
create policy lfs_select on public.payment_late_fee_splits for select
  using (
    unit_id in (
      select u.id from units u join buildings b on b.id = u.building_id
       where b.org_id in (select my_org_ids())
    )
    and (select current_user_is_office_staff())
  );
-- 쓰기는 SECURITY DEFINER RPC 로만 한다.
revoke insert, update, delete, truncate on public.payment_late_fee_splits from anon, authenticated;

alter table public.payments
  add column if not exists late_fee_split_id bigint references public.payment_late_fee_splits(id);
comment on column public.payments.late_fee_split_id is '수.연 행에서 받은 연체료 수납이면 그 미수금 id';
create index if not exists payments_late_fee_split_idx
  on public.payments (late_fee_split_id) where late_fee_split_id is not null;

create or replace function public.create_late_fee_split(
  p_unit_id bigint,
  p_period date,
  p_amount integer,
  p_memo text default null
)
 returns bigint
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_org bigint;
  v_id bigint;
begin
  v_org := current_user_org();
  if v_org is null then raise exception 'no org for caller'; end if;
  if not current_user_has_module('payment') then raise exception 'forbidden: payment required'; end if;
  if not exists (select 1 from units u join buildings b on b.id = u.building_id
                 where u.id = p_unit_id and b.org_id = v_org and u.deleted_at is null) then
    raise exception 'unit not in org'; end if;
  if p_period is null or p_period <> date_trunc('month', p_period)::date then
    raise exception 'period must be first of month'; end if;
  if coalesce(p_amount, 0) <= 0 then raise exception '나눌 연체료가 없어요'; end if;

  insert into payment_late_fee_splits(org_id, unit_id, period, amount, memo, created_by)
    values (v_org, p_unit_id, p_period, p_amount, nullif(p_memo, ''), auth.uid())
    returning id into v_id;

  insert into audit_log(org_id, actor_id, action, table_name, row_pk, after)
    values (v_org, auth.uid(), 'LATE_FEE_SPLIT', 'payment_late_fee_splits', v_id::text,
      jsonb_build_object('unit_id', p_unit_id, 'period', p_period, 'amount', p_amount));
  return v_id;
end $function$;

create or replace function public.cancel_late_fee_split(p_split_id bigint)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_org bigint;
  v_unit bigint;
  v_period date;
begin
  v_org := current_user_org();
  if v_org is null then raise exception 'no org for caller'; end if;
  if not current_user_has_module('payment') then raise exception 'forbidden: payment required'; end if;
  if exists (select 1 from payments p where p.late_fee_split_id = p_split_id and p.status = 'active') then
    raise exception '연체료 수납이 있는 행은 수납을 먼저 삭제해 주세요'; end if;

  update payment_late_fee_splits s set status = 'canceled', canceled_at = now(), canceled_by = auth.uid()
   where s.id = p_split_id and s.org_id = v_org and s.status = 'active'
   returning s.unit_id, s.period into v_unit, v_period;
  if v_unit is null then raise exception 'late fee split not found or already canceled'; end if;

  insert into audit_log(org_id, actor_id, action, table_name, row_pk, after)
    values (v_org, auth.uid(), 'LATE_FEE_SPLIT_CANCEL', 'payment_late_fee_splits', p_split_id::text,
      jsonb_build_object('unit_id', v_unit, 'period', v_period));
end $function$;

revoke all on function public.create_late_fee_split(bigint, date, integer, text) from public, anon;
revoke all on function public.cancel_late_fee_split(bigint) from public, anon;
grant execute on function public.create_late_fee_split(bigint, date, integer, text) to authenticated;
grant execute on function public.cancel_late_fee_split(bigint) to authenticated;

-- 수납을 미수금에 연결한다(같은 호실·월의 살아 있는 미수금만).
create or replace function public.link_payment_late_fee_split(p_payment_id bigint, p_split_id bigint)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
begin
  if p_split_id is null then return; end if;
  update payments p set late_fee_split_id = p_split_id
   where p.id = p_payment_id
     and exists (select 1 from payment_late_fee_splits s
                  where s.id = p_split_id and s.org_id = p.org_id and s.unit_id = p.unit_id
                    and s.period = p.period and s.status = 'active');
  if not found then raise exception '연체료 이전 행을 찾을 수 없어요'; end if;
end $function$;
revoke all on function public.link_payment_late_fee_split(bigint, bigint) from public, anon, authenticated;

create or replace function public.save_payment_history(p_ops jsonb)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_op jsonb;
  v_res jsonb;
  v_split bigint;
  v_canceled int := 0;
  v_recorded int := 0;
  v_edited int := 0;
  v_restored int := 0;
begin
  if not current_user_has_module('payment') then raise exception 'forbidden: payment required'; end if;
  if p_ops is null or jsonb_typeof(p_ops) <> 'array' then raise exception 'ops must be an array'; end if;

  for v_op in select value from jsonb_array_elements(p_ops) loop
    case v_op->>'op'
      when 'cancel' then
        perform cancel_payment((v_op->>'payment_id')::bigint);
        v_canceled := v_canceled + 1;
      when 'restore' then
        perform restore_payment((v_op->>'payment_id')::bigint);
        v_restored := v_restored + 1;
      when 'record' then
        v_res := record_payment(
          (v_op->>'unit_id')::bigint, (v_op->>'period')::date, (v_op->>'amount')::int,
          v_op->>'method', v_op->>'kind', v_op->>'memo', (v_op->>'paid_at')::date,
          coalesce((v_op->>'fee')::int, 0), v_op->>'deposit_type');
        -- 0292: 수.연 행에서 받은 연체료 수납이면 그 미수금에 연결
        perform link_payment_late_fee_split((v_res->>'payment_id')::bigint, (v_op->>'late_fee_split_id')::bigint);
        v_recorded := v_recorded + 1;
      when 'edit' then
        select p.late_fee_split_id into v_split from payments p where p.id = (v_op->>'old_payment_id')::bigint;
        v_res := record_payment_edit(
          (v_op->>'old_payment_id')::bigint,
          (v_op->>'unit_id')::bigint, (v_op->>'period')::date, (v_op->>'amount')::int,
          v_op->>'method', v_op->>'kind', v_op->>'memo', (v_op->>'paid_at')::date,
          (v_op->>'fee')::int, null, v_op->>'deposit_type');
        -- 0292: 수정해도 연체료 이전 행 연결을 유지
        perform link_payment_late_fee_split((v_res->>'payment_id')::bigint, v_split);
        v_edited := v_edited + 1;
      when 'bill' then
        -- 0291: 추가 행 당월계·연체(실제 부과·연체 반영). 같은 달 수납보다 먼저 처리되도록 화면이 앞에 둔다.
        perform set_billing_override(
          (v_op->>'unit_id')::bigint, (v_op->>'period')::date,
          (v_op->>'charged')::int, coalesce((v_op->>'set_charged')::boolean, false),
          (v_op->>'late_fee')::int, coalesce((v_op->>'set_late_fee')::boolean, false));
      when 'split' then
        -- 0292: 수.연 — 연체료를 미수금으로 나누고, 같은 행에 수납액이 있으면 그 수납을 연결한다.
        v_split := create_late_fee_split(
          (v_op->>'unit_id')::bigint, (v_op->>'period')::date,
          (v_op->>'split_amount')::int, v_op->>'split_memo');
        if coalesce((v_op->>'amount')::int, 0) > 0 then
          v_res := record_payment(
            (v_op->>'unit_id')::bigint, (v_op->>'period')::date, (v_op->>'amount')::int,
            v_op->>'method', v_op->>'kind', v_op->>'memo', (v_op->>'paid_at')::date,
            coalesce((v_op->>'fee')::int, 0), v_op->>'deposit_type');
          perform link_payment_late_fee_split((v_res->>'payment_id')::bigint, v_split);
          v_recorded := v_recorded + 1;
        end if;
      when 'cancel_split' then
        perform cancel_late_fee_split((v_op->>'split_id')::bigint);
        v_canceled := v_canceled + 1;
      else
        raise exception 'invalid op: %', v_op->>'op';
    end case;
  end loop;

  return jsonb_build_object('ok', true, 'canceled', v_canceled, 'recorded', v_recorded,
    'edited', v_edited, 'restored', v_restored);
end $function$;

create or replace function public.get_payment_statement_data(p_building_id bigint, p_unit_id bigint, p_start_period date, p_end_period date)
 returns jsonb
 language plpgsql
 stable security definer
 set search_path to 'public'
as $function$
declare
  v_org bigint;
  v_result jsonb;
begin
  v_org := current_user_org();
  if v_org is null then
    raise exception 'no org for caller';
  end if;
  if not exists (
    select 1
    from buildings b
    where b.id = p_building_id
      and b.org_id = v_org
      and b.deleted_at is null
  ) then
    raise exception 'building not in org';
  end if;
  if p_start_period is null
     or p_end_period is null
     or p_start_period <> date_trunc('month', p_start_period)::date
     or p_end_period <> date_trunc('month', p_end_period)::date
     or p_start_period > p_end_period then
    raise exception 'invalid statement period range';
  end if;
  if p_unit_id is not null and not exists (
    select 1
    from units u
    where u.id = p_unit_id
      and u.building_id = p_building_id
      and u.deleted_at is null
  ) then
    raise exception 'unit not in building';
  end if;

  with periods as (
    select generate_series(
      p_start_period::timestamp,
      p_end_period::timestamp,
      interval '1 month'
    )::date as period
  ),
  payment_rows as (
    select periods.period, pr.*
    from periods
    cross join lateral list_payment_rows(p_building_id, periods.period) pr
    where p_unit_id is null or pr.unit_id = p_unit_id
  ),
  statement_units as (
    select pr.period, jsonb_agg(pr.unit_id order by pr.unit_no) as unit_ids
    from payment_rows pr
    group by pr.period
  ),
  documents as (
    select su.period, doc.*
    from statement_units su
    cross join lateral get_bill_documents(
      p_building_id,
      su.period,
      su.unit_ids
    ) doc
  ),
  payment_history as (
    select
      p.id,
      p.unit_id,
      p.period,
      p.amount,
      p.fee,
      p.method,
      p.kind,
      p.memo,
      p.paid_at,
      p.status,
      p.created_at,
      p.replaced_by,
      p.deposit_type,
      p.late_fee_split_id
    from payments p
    join units u on u.id = p.unit_id
    join buildings b
      on b.id = u.building_id
     and b.org_id = v_org
    where u.building_id = p_building_id
      and (p_unit_id is null or p.unit_id = p_unit_id)
      and p.period between p_start_period and p_end_period
  ),
  late_fee_splits as (
    select s.id, s.unit_id, s.period, s.amount, s.memo, s.created_at
    from payment_late_fee_splits s
    join units u on u.id = s.unit_id
    where u.building_id = p_building_id
      and s.org_id = v_org
      and s.status = 'active'
      and (p_unit_id is null or s.unit_id = p_unit_id)
      and s.period between p_start_period and p_end_period
  ),
  utility_kinds as (
    select *
    from (values
      ('electricity'::text, 'elec'::text),
      ('water'::text, 'water'::text),
      ('gas'::text, 'gas'::text)
    ) as value(utility_type, db_utility)
  ),
  utility_rows as (
    select periods.period, uk.utility_type, ur.*
    from periods
    cross join utility_kinds uk
    cross join lateral list_utility_rows(
      p_building_id,
      uk.db_utility,
      periods.period
    ) ur
    where p_unit_id is null or ur.unit_id = p_unit_id
  )
  select jsonb_build_object(
    'payment_rows', coalesce((
      select jsonb_agg(to_jsonb(pr) order by pr.period, pr.unit_no)
      from payment_rows pr
    ), '[]'::jsonb),
    'payments', coalesce((
      select jsonb_agg(
        to_jsonb(ph)
        order by
          case when p_unit_id is null then ph.paid_at end asc,
          case when p_unit_id is not null then ph.created_at end desc,
          ph.id desc
      )
      from payment_history ph
    ), '[]'::jsonb),
    'late_fee_splits', coalesce((
      select jsonb_agg(to_jsonb(s) order by s.period, s.created_at, s.id)
      from late_fee_splits s
    ), '[]'::jsonb),
    'documents', coalesce((
      select jsonb_agg(to_jsonb(doc) order by doc.period, doc.unit_no)
      from documents doc
    ), '[]'::jsonb),
    'utilities', jsonb_build_object(
      'electricity', coalesce((
        select jsonb_agg(
          to_jsonb(ur) - 'utility_type'
          order by ur.period, ur.unit_no
        )
        from utility_rows ur
        where ur.utility_type = 'electricity'
      ), '[]'::jsonb),
      'water', coalesce((
        select jsonb_agg(
          to_jsonb(ur) - 'utility_type'
          order by ur.period, ur.unit_no
        )
        from utility_rows ur
        where ur.utility_type = 'water'
      ), '[]'::jsonb),
      'gas', coalesce((
        select jsonb_agg(
          to_jsonb(ur) - 'utility_type'
          order by ur.period, ur.unit_no
        )
        from utility_rows ur
        where ur.utility_type = 'gas'
      ), '[]'::jsonb)
    )
  ) into v_result;

  return v_result;
end;
$function$;
